CREATE TABLE IF NOT EXISTS ql_users (
 id CHAR(32) PRIMARY KEY, username VARCHAR(60) NOT NULL UNIQUE,
 display VARCHAR(120) NOT NULL, role VARCHAR(16) NOT NULL,
 password VARCHAR(100) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 created TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_sessions (
 token CHAR(64) PRIMARY KEY, user_id CHAR(32) NOT NULL,
 csrf CHAR(64) NOT NULL, expires BIGINT NOT NULL,
 space_kind VARCHAR(16) NOT NULL DEFAULT 'personal' COMMENT '本会话所在空间：personal|team|platform（见 migrations/005）',
 space_id BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '团队/平台空间 id；个人空间为 0',
 FOREIGN KEY(user_id) REFERENCES ql_users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_workbench_accounts (
 user_id CHAR(32) PRIMARY KEY,
 workbench_user_id BIGINT NOT NULL UNIQUE,
 email VARCHAR(255) NOT NULL DEFAULT '',
 display_name VARCHAR(120) NOT NULL DEFAULT '',
 service_role VARCHAR(32) NOT NULL DEFAULT '',
 access_token VARBINARY(4096) NULL,
 refresh_token VARBINARY(4096) NULL,
 token_expires BIGINT NOT NULL DEFAULT 0,
 permissions JSON NULL COMMENT '工作台权限码快照（见 server/permissions.go）',
 updated TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 FOREIGN KEY(user_id) REFERENCES ql_users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_customers (
 id CHAR(32) PRIMARY KEY, name VARCHAR(120) NOT NULL, payload JSON NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1, created TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_grants (
 customer_id CHAR(32) NOT NULL, user_id CHAR(32) NOT NULL,
 PRIMARY KEY(customer_id,user_id),
 FOREIGN KEY(customer_id) REFERENCES ql_customers(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES ql_users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_documents (
 id CHAR(32) PRIMARY KEY, customer_id CHAR(32) NOT NULL, sha CHAR(64) NOT NULL,
 name VARCHAR(240) NOT NULL, payload JSON NOT NULL, created TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE(customer_id,sha), FOREIGN KEY(customer_id) REFERENCES ql_customers(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_transactions (
 seq BIGINT AUTO_INCREMENT PRIMARY KEY, id CHAR(32) NOT NULL UNIQUE,
 customer_id CHAR(32) NOT NULL, document_id CHAR(32) NOT NULL, fingerprint CHAR(64) NOT NULL,
 payload JSON NOT NULL, INDEX(customer_id,fingerprint),
 FOREIGN KEY(customer_id) REFERENCES ql_customers(id) ON DELETE CASCADE,
 FOREIGN KEY(document_id) REFERENCES ql_documents(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_reviews (
 seq BIGINT AUTO_INCREMENT PRIMARY KEY, transaction_id CHAR(32) NOT NULL,
 label VARCHAR(20) NOT NULL, operator VARCHAR(120) NOT NULL, reason TEXT NOT NULL,
 created TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(transaction_id) REFERENCES ql_transactions(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_jobs (
 seq BIGINT AUTO_INCREMENT PRIMARY KEY, id CHAR(32) NOT NULL UNIQUE, customer_id CHAR(32) NOT NULL,
 user_id CHAR(32) NOT NULL, kind VARCHAR(16) NOT NULL, status VARCHAR(16) NOT NULL,
 payload JSON NOT NULL, message VARCHAR(1000) NOT NULL,
 progress INT NOT NULL DEFAULT 0, stage VARCHAR(32) NOT NULL DEFAULT '',
 upload_batch VARCHAR(64) NOT NULL DEFAULT '',
 space_kind VARCHAR(16) NOT NULL DEFAULT 'personal' COMMENT '任务提交时所在的空间（见 migrations/005）',
 space_id BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '团队空间 id；个人空间为 0',
 created TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), INDEX(status,seq), INDEX(customer_id,upload_batch),
 FOREIGN KEY(customer_id) REFERENCES ql_customers(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_submissions (
 customer_id CHAR(32) PRIMARY KEY, revision BIGINT NOT NULL, payload JSON NOT NULL,
 FOREIGN KEY(customer_id) REFERENCES ql_customers(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_reports (
 seq BIGINT AUTO_INCREMENT PRIMARY KEY, id CHAR(32) NOT NULL UNIQUE, customer_id CHAR(32) NOT NULL,
 job_id CHAR(32) NOT NULL UNIQUE, payload JSON NOT NULL,
 created TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(customer_id) REFERENCES ql_customers(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_events (
 seq BIGINT AUTO_INCREMENT PRIMARY KEY, user_id CHAR(32) NOT NULL, customer_id CHAR(32),
 action VARCHAR(60) NOT NULL, detail VARCHAR(500) NOT NULL,
 created TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 INDEX(user_id,seq), INDEX(action,seq), INDEX(created,seq)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_login_failures (
 failure_key CHAR(64) NOT NULL, at BIGINT NOT NULL, INDEX(failure_key,at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_ai_analyses (
 id CHAR(32) PRIMARY KEY,
 customer_id CHAR(32) NOT NULL,
 document_id CHAR(32) NOT NULL,
 workbench_document_id BIGINT NOT NULL DEFAULT 0,
 workbench_analysis_id BIGINT NOT NULL DEFAULT 0,
 status VARCHAR(16) NOT NULL DEFAULT 'queued',
 progress INT NOT NULL DEFAULT 0,
 stage VARCHAR(32) NOT NULL DEFAULT 'uploading',
 result JSON NULL,
 error VARCHAR(1024) NOT NULL DEFAULT '',
 created TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 completed TIMESTAMP(6) NULL DEFAULT NULL,
 FOREIGN KEY(customer_id) REFERENCES ql_customers(id) ON DELETE CASCADE,
 FOREIGN KEY(document_id) REFERENCES ql_documents(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ql_upload_batches (
 customer_id CHAR(32) NOT NULL, batch CHAR(64) NOT NULL,
 payload JSON NOT NULL,
 created TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(customer_id,batch),
 FOREIGN KEY(customer_id) REFERENCES ql_customers(id) ON DELETE CASCADE
) ENGINE=InnoDB;
